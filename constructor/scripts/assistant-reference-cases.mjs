export function referenceLecture() {
  return Array.from({ length: 84 }, (_, i) => {
    const page = i + 1;
    const anchor = anchors.find((item) => item.page === page);
    const parts = Array.from(
      { length: 5 },
      (_, j) => paragraphs[(i * 3 + j) % paragraphs.length],
    );
    if (anchor)
      parts.splice(
        2,
        0,
        `Условие для справочного задания. ${anchor.phrase} — ${anchor.value}.`,
      );
    return {
      locator: "с. " + page,
      text: [sections[i % sections.length], ...parts].join("\n\n"),
    };
  });
}
