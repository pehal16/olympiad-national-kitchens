const fs=require('node:fs');
const path=require('node:path');
const {spawn}=require('node:child_process');
const os=require('node:os');
const root=__dirname,port=Number(process.env.CONSTRUCTOR_PORT||3210);
const data=path.resolve(process.env.CONSTRUCTOR_STORAGE||path.join(root,'data'));
const browser=path.join(root,'runtime','browser','chrome.exe');
if(!fs.existsSync(browser))throw new Error('Не найден браузер PDF. Распакуйте комплект полностью.');
process.chdir(path.join(root,'app'));
console.log('Полный конструктор олимпиад · локальная установка');
console.log('Папка данных: '+data);
console.log('Кабинет: http://127.0.0.1:'+port+'/constructor/');
for(const list of Object.values(os.networkInterfaces()))for(const address of list||[])if(address.family==='IPv4'&&!address.internal)console.log('Участники в локальной сети: http://'+address.address+':'+port+'/constructor/');
console.log('Для подключения с других компьютеров разрешите входящие TCP-соединения на порт '+port+' только в доверенной сети колледжа.');
console.log('Оставьте это окно открытым. Для остановки нажмите Ctrl+C.');
const child=spawn(process.execPath,['server.cjs'],{stdio:'inherit',windowsHide:true,env:{...process.env,CONSTRUCTOR_STORAGE:data,CONSTRUCTOR_HOST:process.env.CONSTRUCTOR_HOST||'0.0.0.0',CONSTRUCTOR_PORT:String(port),CONSTRUCTOR_CHROMIUM:browser,CONSTRUCTOR_MODE:'local',CONSTRUCTOR_ASSET_ROOT:path.join(root,'app','client')}});
child.on('error',error=>{console.error(error.message);process.exitCode=1;});
child.on('exit',code=>{process.exitCode=code||0;});
process.on('SIGINT',()=>child.kill('SIGINT'));
